#!/usr/bin/env node
// Bundles the Rauri module tree into one Luau file.
// Roblox-style requires (script.Parent.foo, ReplicatedStorage.Rauri) are
// rewritten to a tiny module registry so the result runs headless or in an
// executor, as well as serving as the test harness loader.
//
// usage: node scripts/bundle.mjs --entry <file> --out <file>
//          [--prepend <file>] [--alias Name=dir]...

import fs from 'node:fs'
import path from 'node:path'

const args = process.argv.slice(2)
const options = { aliases: {} }
for (let index = 0; index < args.length; index++) {
	const arg = args[index]
	if (arg === '--entry') options.entry = args[++index]
	else if (arg === '--out') options.out = args[++index]
	else if (arg === '--prepend') options.prepend = args[++index]
	else if (arg === '--alias') {
		const assignment = args[++index] ?? ''
		const split = assignment.indexOf('=')
		if (split === -1) {
			console.error(`bad alias: ${assignment}`)
			process.exit(1)
		}
		options.aliases[assignment.slice(0, split)] = assignment.slice(split + 1)
	}
}

if (!options.entry || !options.out) {
	console.error('usage: node scripts/bundle.mjs --entry <file> --out <file> [--prepend <file>] [--alias Name=dir]')
	process.exit(1)
}

const root = process.cwd()

function instancePath(file) {
	let relative = path.relative(root, file).split(path.sep).join('/')
	relative = relative.replace(/\.(lua|luau)$/, '')
	relative = relative.replace(/\.(client|server)$/, '')
	if (relative.endsWith('/init')) relative = relative.slice(0, -5)
	return relative
}

function resolveFile(base) {
	const candidates = [
		`${base}.lua`,
		`${base}.luau`,
		`${base}.client.lua`,
		`${base}.server.lua`,
		`${base}/init.lua`,
		`${base}/init.luau`,
	]
	for (const candidate of candidates) {
		if (fs.existsSync(candidate) && fs.statSync(candidate).isFile()) return candidate
	}
	return null
}

function resolveExpression(expression, currentPath) {
	const segments = expression.split('.')
	let base
	if (segments[0] === 'script') {
		base = currentPath
		segments.shift()
	} else if (options.aliases[segments[0]]) {
		base = options.aliases[segments[0]]
		segments.shift()
	} else {
		return null
	}
	for (const segment of segments) {
		if (segment === 'Parent') base = base.includes('/') ? base.slice(0, base.lastIndexOf('/')) : ''
		else base = base ? `${base}/${segment}` : segment
	}
	return base
}

const sources = new Map()

function collect(file) {
	const id = instancePath(file)
	if (sources.has(id)) return
	sources.set(id, new Map())
	const code = fs.readFileSync(file, 'utf8')
	const rewritten = code.replace(/require\(\s*([A-Za-z_][A-Za-z0-9_.]*)\s*\)/g, (match, expression) => {
		const base = resolveExpression(expression, id)
		if (base === null) return match
		const target = resolveFile(base)
		if (!target) {
			console.error(`cannot resolve require(${expression}) from ${path.relative(root, file)}`)
			process.exitCode = 1
			return match
		}
		collect(target)
		return `__require(${JSON.stringify(instancePath(target))})`
	})
	sources.set(id, rewritten)
}

const entryFile = resolveFile(options.entry.replace(/\.(lua|luau)$/, '')) ?? options.entry
collect(entryFile)

const chunks = []
if (options.prepend) {
	chunks.push(fs.readFileSync(options.prepend, 'utf8').trimEnd())
}
chunks.push('--!nolint')
chunks.push('-- Generated by scripts/bundle.mjs. Do not edit directly.')
chunks.push('local __modules = {}')
chunks.push('local __cache = {}')
chunks.push(`local function __require(id)
	local cached = __cache[id]
	if cached ~= nil then
		return cached
	end
	local factory = __modules[id]
	if not factory then
		error("Rauri bundle: missing module " .. tostring(id))
	end
	local value = factory()
	__cache[id] = value
	return value
end`)

for (const [id, code] of sources) {
	chunks.push(`__modules[${JSON.stringify(id)}] = function()`)
	chunks.push(code.trimEnd())
	chunks.push('end')
}

chunks.push(`return __require(${JSON.stringify(instancePath(entryFile))})`)

fs.mkdirSync(path.dirname(options.out), { recursive: true })
fs.writeFileSync(options.out, `${chunks.join('\n')}\n`)
console.log(`bundled ${sources.size} modules -> ${options.out}`)
